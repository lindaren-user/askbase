-- 消息引用独立保存检索时分数，历史消息无需重新检索即可还原引用元数据。
CREATE TABLE IF NOT EXISTS t_message_citation (
    message_id BIGINT NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    chunk_id BIGINT NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (message_id, position)
);

COMMENT ON TABLE t_message_citation IS '助手消息引用的分块及检索时元数据';
COMMENT ON COLUMN t_message_citation.message_id IS '所属助手消息 ID';
COMMENT ON COLUMN t_message_citation.position IS '引用编号，对应回答中的 [n]';
COMMENT ON COLUMN t_message_citation.chunk_id IS '引用的 t_chunk ID';
COMMENT ON COLUMN t_message_citation.score IS '生成回答时的检索分数';

CREATE INDEX IF NOT EXISTS idx_t_message_citation_chunk_id ON t_message_citation (chunk_id);
