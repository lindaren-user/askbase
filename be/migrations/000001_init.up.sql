CREATE TABLE IF NOT EXISTS t_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    nickname VARCHAR(64) NOT NULL DEFAULT '',
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE t_user IS '用户表，邮箱验证码登录，不保存密码';
COMMENT ON COLUMN t_user.id IS '用户 ID，自增主键';
COMMENT ON COLUMN t_user.email IS '登录邮箱，唯一，统一按小写存储';
COMMENT ON COLUMN t_user.nickname IS '显示昵称，默认取邮箱 @ 前一段';
COMMENT ON COLUMN t_user.status IS '用户状态：1=正常，2=禁用';
COMMENT ON COLUMN t_user.created_at IS '创建时间，带时区';
COMMENT ON COLUMN t_user.updated_at IS '更新时间，带时区';

ALTER TABLE t_user ADD CONSTRAINT t_user_email_key UNIQUE (email);

