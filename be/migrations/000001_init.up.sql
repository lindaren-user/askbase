CREATE EXTENSION IF NOT EXISTS vector;

-- 英文按完整单词建立词元；中文同时生成单字和相邻双字词元。
CREATE OR REPLACE FUNCTION askbase_search_tokens(input TEXT)
RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
AS $$
DECLARE
    source TEXT := lower(COALESCE(input, ''));
    tokens TEXT[] := ARRAY[]::TEXT[];
    ascii_token TEXT := '';
    previous_cjk TEXT := '';
    ch TEXT;
    codepoint INTEGER;
    i INTEGER;
BEGIN
    FOR i IN 1..char_length(source) LOOP
        ch := substr(source, i, 1);
        codepoint := ascii(ch);
        IF codepoint BETWEEN 48 AND 57
            OR codepoint BETWEEN 97 AND 122
            OR ch = '_' THEN
            ascii_token := ascii_token || ch;
            previous_cjk := '';
            CONTINUE;
        END IF;
        IF ascii_token <> '' THEN
            tokens := array_append(tokens, ascii_token);
            ascii_token := '';
        END IF;
        IF codepoint BETWEEN 13312 AND 40959 THEN
            tokens := array_append(tokens, ch);
            IF previous_cjk <> '' THEN
                tokens := array_append(tokens, previous_cjk || ch);
            END IF;
            previous_cjk := ch;
        ELSE
            previous_cjk := '';
        END IF;
    END LOOP;
    IF ascii_token <> '' THEN
        tokens := array_append(tokens, ascii_token);
    END IF;
    RETURN array_to_string(tokens, ' ');
END;
$$;

CREATE OR REPLACE FUNCTION askbase_search_query(input TEXT)
RETURNS TSQUERY
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
    SELECT to_tsquery(
        'simple',
        regexp_replace(NULLIF(btrim(askbase_search_tokens(input)), ''), '\s+', ' | ', 'g')
    );
$$;

-- ============================================================================
-- 1. 用户表
