-- 4. 事务 Outbox
-- ============================================================================
CREATE TABLE IF NOT EXISTS t_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic VARCHAR(128) NOT NULL,
    aggregate_id BIGINT NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    publish_attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE t_outbox IS '事务消息表；relay 可靠发布到 RabbitMQ 后标记 published';
COMMENT ON COLUMN t_outbox.topic IS '消息主题';
COMMENT ON COLUMN t_outbox.aggregate_id IS '关联业务实体 ID';
COMMENT ON COLUMN t_outbox.payload IS '待发布 JSON 消息体';
COMMENT ON COLUMN t_outbox.status IS '发布状态：pending 或 published';
COMMENT ON COLUMN t_outbox.publish_attempts IS '发布尝试次数';
COMMENT ON COLUMN t_outbox.next_attempt_at IS '下次允许发布时间';
COMMENT ON COLUMN t_outbox.published_at IS 'RabbitMQ publisher confirm 成功时间';
COMMENT ON COLUMN t_outbox.last_error IS '最近一次发布错误';

CREATE INDEX IF NOT EXISTS idx_t_outbox_pending ON t_outbox (next_attempt_at, id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_t_outbox_published_at ON t_outbox (published_at) WHERE status = 'published';

-- ============================================================================
-- 5. 分块表
-- ============================================================================
CREATE TABLE IF NOT EXISTS t_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    dataset_id BIGINT NOT NULL,
    chunk_index INT NOT NULL DEFAULT 0,
    content TEXT NOT NULL,
    token_num INT NOT NULL DEFAULT 0,
    image_key TEXT NOT NULL DEFAULT '',
    element_type VARCHAR(32) NOT NULL DEFAULT 'text',
    page_number INTEGER NOT NULL DEFAULT 0,
    bbox JSONB NOT NULL DEFAULT '[]'::jsonb,
    parser_name VARCHAR(64) NOT NULL DEFAULT '',
    search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', askbase_search_tokens(content))) STORED,
    q_1024_vec vector(1024),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE t_chunk IS '文档分块表，向量化后参与检索';
COMMENT ON COLUMN t_chunk.id IS '分块 ID，自增主键';
COMMENT ON COLUMN t_chunk.document_id IS '所属文档 ID';
COMMENT ON COLUMN t_chunk.dataset_id IS '冗余知识库 ID，检索时免 join 文档表';
COMMENT ON COLUMN t_chunk.chunk_index IS '块在文档内的序号，从 0 开始';
COMMENT ON COLUMN t_chunk.content IS '分块文本内容';
COMMENT ON COLUMN t_chunk.image_key IS '图片原子在对象存储中的 key，空表示纯文本块';
COMMENT ON COLUMN t_chunk.element_type IS '来源元素类型：text/title/table/formula/image/chart/code/list';
COMMENT ON COLUMN t_chunk.page_number IS '元素所在 PDF 页码，从 1 开始；0 表示未知或非分页文档';
COMMENT ON COLUMN t_chunk.bbox IS '元素在页面内的坐标框，由解析器原样返回';
COMMENT ON COLUMN t_chunk.parser_name IS '产生该分块的解析器及模型版本';
COMMENT ON COLUMN t_chunk.search_vector IS '中英文全文检索向量：英文单词、中文单字与相邻双字词元';
COMMENT ON COLUMN t_chunk.token_num IS '分块 token 估算数（按 rune 估算）';
COMMENT ON COLUMN t_chunk.q_1024_vec IS '1024 维嵌入；其它维度按 q_N_vec 动态加列';
COMMENT ON COLUMN t_chunk.enabled IS '是否启用；禁用后不参与检索';
COMMENT ON COLUMN t_chunk.created_at IS '创建时间，带时区';
COMMENT ON COLUMN t_chunk.updated_at IS '更新时间，带时区';

CREATE INDEX IF NOT EXISTS idx_t_chunk_document_id ON t_chunk (document_id);
CREATE INDEX IF NOT EXISTS idx_t_chunk_dataset_id ON t_chunk (dataset_id);
-- 向量近邻索引（余弦）；数据量小也能建，pgvector 自动退化为精确检索
CREATE INDEX IF NOT EXISTS idx_t_chunk_q_1024_vec_hnsw ON t_chunk USING hnsw (q_1024_vec vector_cosine_ops);
CREATE INDEX IF NOT EXISTS idx_t_chunk_search_vector_gin ON t_chunk USING gin (search_vector);

